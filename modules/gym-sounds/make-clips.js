// Writes clips.js (base64 copies of the recorded sounds) from the .mp3 files next to it.
// Run after changing an mp3: node modules/gym-sounds/make-clips.js
const fs = require("fs"), path = require("path");
const CLIPS = { check: "check.mp3" };
function source() {
  const lines = Object.entries(CLIPS).map(([id, f]) => `  ${id}: "${fs.readFileSync(path.join(__dirname, f)).toString("base64")}"`);
  return "// GENERATED by make-clips.js from the .mp3 files in this folder. Do not edit.\n" +
    "// check: Aziz's own set-check sound (Nov 2, 2026), trimmed to the chime, denoised, normalised.\n" +
    "(function (root) {\n  const GymSoundClips = {\n" + lines.join(",\n") + "\n  };\n" +
    "  root.GymSoundClips = GymSoundClips;\n  if (typeof module !== 'undefined' && module.exports) module.exports = GymSoundClips;\n" +
    "})(typeof window !== 'undefined' ? window : globalThis);\n";
}
if (require.main === module) fs.writeFileSync(path.join(__dirname, "clips.js"), source());
module.exports = { source };
